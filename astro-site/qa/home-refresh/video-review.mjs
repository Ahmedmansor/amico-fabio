import {writeFile,mkdir} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser=await chromium.launch({headless:true,executablePath:process.env.QA_BROWSER});
const report={};
await mkdir(new URL('./screenshots/after/',import.meta.url),{recursive:true});
try{
 const page=await browser.newPage({viewport:{width:1280,height:900},reducedMotion:'reduce'}),requests=[];
 page.on('request',r=>requests.push(r.url()));
 await page.goto('http://127.0.0.1:4333/en/');
 const consent=await page.locator('#cookie-consent-config').evaluate(n=>JSON.parse(n.textContent).messages);
 await page.getByRole('button',{name:consent.reject,exact:true}).first().click();
 report.reducedMotionChunkAbsent=!requests.some(url=>url.includes('home-motion'));
 report.reducedMotionPoster=await page.locator('.wf-scene').evaluate(n=>getComputedStyle(n).transform==='none');
 await page.locator('[data-home-video]').first().click();
 report.preferencesBeforeEmbed=await page.locator('#cc-main input[value=external]').isVisible();
 report.noVimeoWithoutConsent=!requests.some(url=>url.includes('vimeo.com'));
 await page.locator('#cc-main input[value=external]').check();
 await page.getByRole('button',{name:consent.save,exact:true}).click();
 const response=page.waitForResponse(r=>r.url().startsWith('https://player.vimeo.com/video/1214756632'),{timeout:20000}).catch(()=>null);
 await page.locator('[data-home-video]').first().click();
 report.dialogOpens=await page.locator('.home-video-dialog').evaluate(n=>n.open);
 report.iframe=await page.locator('.home-video-player iframe').getAttribute('src');
 const loaded=await response;report.playerHttpStatus=loaded?.status()??null;
 const player=page.frameLocator('.home-video-player iframe');
 await player.locator('video').first().waitFor({state:'attached',timeout:15000}).catch(()=>{});
 report.playerVideoElement=await player.locator('video').count();
 await page.screenshot({path:new URL('./screenshots/after/vimeo-dialog.png',import.meta.url).pathname.replace(/^\/(?=[A-Z]:)/,'')});
 await page.locator('[data-close-home-video]').click();
 report.closeUnloadsPlayer=await page.locator('.home-video-player iframe').count()===0;
 await page.locator('[data-home-video]').first().click();await page.keyboard.press('Escape');
 report.escapeUnloadsPlayer=!(await page.locator('.home-video-dialog').evaluate(n=>n.open))&&await page.locator('.home-video-player iframe').count()===0;
 const cookie=await page.context().cookies();const selected=JSON.parse(decodeURIComponent(cookie.find(c=>c.name==='fabio_consent').value));report.analyticsNotEnabled=!selected.categories.includes('analytics');
 const campaign=await browser.newPage({viewport:{width:1280,height:900}});await campaign.goto('http://127.0.0.1:4333/offerta-sharm/');
 report.campaignVideos=await campaign.locator('[data-video-id]').count();
 report.campaignIDs=await campaign.locator('[data-video-id]').evaluateAll(nodes=>nodes.map(n=>n.dataset.videoId));
}finally{await browser.close();}
await writeFile(new URL('./video-review.json',import.meta.url),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
if(!report.reducedMotionChunkAbsent||!report.reducedMotionPoster||!report.noVimeoWithoutConsent||!report.dialogOpens||!report.closeUnloadsPlayer||!report.escapeUnloadsPlayer||!report.analyticsNotEnabled||report.campaignVideos!==6)process.exitCode=1;
